"""Build every paper table and figure from the results CSVs.

    python make_paper_assets.py

Reads results/{benchmark,hw_share,calibration}_{hf,sn}.csv and
results/prior_sensitivity_sn*.csv; writes results/paper_assets/:
  tables  : <name>.csv and <name>.tex (booktabs; \\usepackage{booktabs})
  figures : <name>.pdf
  numbers.md : every number the paper cites, with the file it comes from
Nothing here fits a model; rerun the producing scripts first.
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.colors import LinearSegmentedColormap, LogNorm  # noqa: E402

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = RES / "paper_assets"

STAGE_LABEL = {"hf": "Heuristic filtering", "sn": "String normalisation"}
GROUPS = [
    ("No metadata", ["bhm", "complete_pooling", "no_pooling", "rf", "gbm", "gp", "mlp"]),
    ("Curated metadata", ["bhm+meta", "bhm+meta_slope", "rf+meta", "gbm+meta", "gp+meta", "mlp+meta"]),
    ("All metadata (exploratory)", ["rf+meta_all", "gbm+meta_all", "gp+meta_all", "mlp+meta_all"]),
]
BASE_LABEL = {"bhm": "BHM", "complete_pooling": "Complete pooling", "no_pooling": "No pooling",
              "rf": "Random forest", "gbm": "Gradient boosting", "gp": "Gaussian process", "mlp": "MLP"}
VARIANT_LABEL = {"": "", "meta": " + meta", "meta_slope": " + meta (int.+slope)", "meta_all": " + all meta"}
EXPLORATORY = {m for m in GROUPS[2][1]}
MODEL_ORDER = [m for _, ms in GROUPS for m in ms]
MODEL_GROUP = {m: g for g, ms in GROUPS for m in ms}

# reference palette (dataviz skill): sequential blue ramp + text/neutral tokens
BLUE_RAMP = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]
BLUE = "#2a78d6"
TEXT, TEXT_2, GRID, NEUTRAL = "#0b0b0b", "#52514e", "#e4e3df", "#9b9a95"


def label(model: str) -> str:
    base, _, variant = model.partition("+")
    return BASE_LABEL[base] + VARIANT_LABEL[variant] + ("$^\\dagger$" if model in EXPLORATORY else "")


def plain_label(model: str) -> str:
    return label(model).replace("$^\\dagger$", "†")


def short_corpus(c: str) -> str:
    return c.removesuffix("_str_norm")


# ── numbers registry ─────────────────────────────────────────────────────────

NUMBERS: list[dict] = []


def cite(key: str, value, desc: str, source: str, fmt: str = "{:.1f}"):
    text = value if isinstance(value, str) else fmt.format(value)
    NUMBERS.append({"key": key, "value": text, "description": desc, "source": source})
    return value


# ── LaTeX ────────────────────────────────────────────────────────────────────

def tex_escape(s: str) -> str:
    if "$" in s:  # already LaTeX (e.g. dagger) — escape only outside math
        head, _, tail = s.partition("$")
        math, _, rest = tail.partition("$")
        return tex_escape(head) + f"${math}$" + tex_escape(rest)
    return s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def _plain(s) -> str:
    return str(s).replace("$^\\dagger$", "†").replace("$\\tau$", "τ").replace("\\%", "%")


def write_table(df: pd.DataFrame, name: str, caption: str, notes: str = "",
                group_col: str | None = None, index_label: str = "", float_fmt: str | None = None) -> None:
    """CSV (raw values, plain-text labels) + booktabs LaTeX; a group_col becomes
    \\midrule-separated blocks."""
    csv = df.rename(index=_plain, columns=_plain)
    csv.index.name = csv.index.name or "row"
    csv.to_csv(OUT / f"{name}.csv")
    show = df.drop(columns=[group_col]) if group_col else df
    cols = [index_label] + [str(c) for c in show.columns]
    lines = [
        "% generated by make_paper_assets.py — do not edit",
        "\\begin{table}[t]", "\\centering", "\\small",
        f"\\caption{{{caption}}}", f"\\label{{tab:{name}}}",
        f"\\begin{{tabular}}{{l{'r' * show.shape[1]}}}", "\\toprule",
        " & ".join(tex_escape(c) for c in cols) + " \\\\", "\\midrule",
    ]
    prev = None
    groups = df[group_col].tolist() if group_col else [None] * len(show)
    for (idx, row), g in zip(show.iterrows(), groups):
        if group_col:
            if g != prev:
                if prev is not None:
                    lines.append("\\midrule")
                lines.append(f"\\multicolumn{{{len(cols)}}}{{l}}{{\\textit{{{tex_escape(g)}}}}} \\\\")
                prev = g
        cells = [tex_escape(str(idx))] + [tex_escape(_fmt(v, float_fmt)) for v in row]
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        lines.append(f"\\par\\smallskip\\footnotesize {tex_escape(notes)}")
    lines.append("\\end{table}")
    (OUT / f"{name}.tex").write_text("\n".join(lines) + "\n")


def _fmt(v, float_fmt: str | None = None) -> str:
    if isinstance(v, str):
        return v
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "--"
    if isinstance(v, (int, np.integer)):
        return str(v)
    if float_fmt:
        return float_fmt.format(v)
    return f"{v:.0f}" if abs(v) >= 100 else f"{v:.1f}"


# ── loading ──────────────────────────────────────────────────────────────────

def load_benchmark(stage: str) -> pd.DataFrame:
    b = pd.read_csv(RES / f"benchmark_{stage}.csv")
    b = b[b["condition"] == "zero_shot"].copy()
    b["corpus"] = b["corpus"].map(short_corpus)
    return b


def ordered_models(models) -> list[str]:
    present = set(models)
    return [m for m in MODEL_ORDER if m in present]


# ── tables ───────────────────────────────────────────────────────────────────

def table_zero_shot(bench: dict[str, pd.DataFrame]) -> None:
    rows = {}
    for st, b in bench.items():
        src = f"results/benchmark_{st}.csv"
        for m, g in b.groupby("model"):
            r = rows.setdefault(m, {"group": MODEL_GROUP[m]})
            ok = g["rt_mape"].notna()
            r[f"{st} RT MAPE median"] = g["rt_mape"].median() if ok.any() else np.nan
            r[f"{st} E MAPE median"] = g["e_mape"].median() if ok.any() else np.nan
            r[f"{st} RT MAPE mean"] = g["rt_mape"].mean() if ok.any() else np.nan
            r[f"{st} corpus cov."] = f"{int(g['corpus_cov94'].sum())}/{int(ok.sum())}" if ok.any() else "--"
            if ok.any():
                for metric in ("rt_mape", "e_mape"):
                    cite(f"zs.{st}.{m}.{metric}_median", g[metric].median(),
                         f"{STAGE_LABEL[st]}, zero-shot, {plain_label(m)}: median {metric} over corpora (%)",
                         f"{src} (condition=zero_shot, model={m}, median of {metric})")
    df = pd.DataFrame.from_dict(rows, orient="index").loc[ordered_models(rows)]
    df.index = [label(m) for m in df.index]
    write_table(df, "zero_shot_benchmark",
                "Zero-shot (leave-one-corpus-out) prediction error. MAPE of the per-job median prediction "
                "against measured means per configuration cell, summarised over held-out corpora; corpus "
                "cov. counts folds whose corpus-level mean log runtime per character lies in the 94\\% "
                "interval.",
                notes="$^\\dagger$ exploratory: all 44 available corpus features learned from 5–8 training corpora. "
                      "No pooling cannot predict an unseen corpus.",
                group_col="group")


def table_per_corpus(bench: dict[str, pd.DataFrame]) -> None:
    for st, b in bench.items():
        for metric, name in (("rt_mape", "runtime"), ("e_mape", "energy")):
            wide = b.pivot(index="model", columns="corpus", values=metric)
            wide = wide.loc[[m for m in ordered_models(wide.index) if wide.loc[m].notna().any()]]
            wide.insert(0, "group", [MODEL_GROUP[m] for m in wide.index])
            wide.index = [label(m) for m in wide.index]
            write_table(wide, f"per_corpus_{st}_{name}",
                        f"{STAGE_LABEL[st]}: zero-shot {name} MAPE (\\%) per held-out corpus.",
                        notes="$^\\dagger$ exploratory (all metadata features).", group_col="group")


def table_hw_share() -> None:
    for st in ("hf", "sn"):
        src = f"results/hw_share_{st}.csv"
        hw = pd.read_csv(RES / src.removeprefix("results/"), index_col="corpus") * 100
        hw.index = [short_corpus(c) for c in hw.index]
        for regime in hw.columns:
            for row in ("median", "pooled"):
                v = hw.at[row, regime]
                if pd.notna(v):
                    cite(f"hw.{st}.{regime}.{row}", v, f"{STAGE_LABEL[st]}: hardware share of energy variance, "
                         f"{regime}, {row} (%)", f"{src} (row={row}, column={regime})")
        hw.columns = ["In-sample (with $\\tau$)", "Zero-shot", "Anchored", "Thesis-style (no $\\tau$)"]
        write_table(hw, f"hw_share_{st}",
                    f"{STAGE_LABEL[st]}: hardware (power) share of BHM energy variance, \\%, by regime.",
                    notes="Job-level, summed over a corpus's jobs. Thesis-style omits observation noise and is "
                          "shown only for comparison with the thesis. Pooled sums variances over all jobs. "
                          "Anchored pending probe runs.")


def table_calibration() -> pd.DataFrame:
    frames = []
    for st in ("hf", "sn"):
        c = pd.read_csv(RES / f"calibration_{st}.csv")
        g = c.groupby("model").agg(cov=("in_hdi94", "mean"), n=("pit", "size"))
        for m, r in g.iterrows():
            cite(f"cal.{st}.{m}.cov94", 100 * r["cov"], f"{STAGE_LABEL[st]}, in-sample, {plain_label(m)}: "
                 f"share of jobs in 94% interval (%)", f"results/calibration_{st}.csv (model={m}, mean of in_hdi94)")
        cite(f"cal.{st}.n_jobs", int(g["n"].iloc[0]), f"{STAGE_LABEL[st]}: jobs in calibration",
             f"results/calibration_{st}.csv", fmt="{:d}")
        frames.append((100 * g["cov"]).rename(f"{st} 94\\% cov."))
    df = pd.concat(frames, axis=1).loc[ordered_models(frames[0].index)]
    df.index = [label(m) for m in df.index]
    write_table(df, "calibration_in_sample",
                "In-sample calibration: share of jobs (\\%) whose measured runtime lies in the 94\\% "
                "predictive interval (nominal 94).",
                notes="BHM: production fits. Baselines refit on all jobs.")
    return df


def table_convergence(bench: dict[str, pd.DataFrame]) -> None:
    rows = []
    for st, b in bench.items():
        bhm = b[b["model"].str.startswith("bhm")]
        for _, r in bhm.iterrows():
            rows.append({"stage": st, "model": r["model"], "corpus": r["corpus"],
                         "divergences": int(r["divergences"]), "R-hat max": round(r["rhat_max"], 4)})
        settings = {k.removeprefix("mcmc_"): bhm[k].iloc[0] for k in bhm.columns if k.startswith("mcmc_")}
        cite(f"conv.{st}.divergences_total", int(bhm["divergences"].sum()),
             f"{STAGE_LABEL[st]}: total divergent transitions over all BHM zero-shot fits",
             f"results/benchmark_{st}.csv (model=bhm*, sum of divergences)", fmt="{:d}")
        cite(f"conv.{st}.rhat_max", bhm["rhat_max"].max(), f"{STAGE_LABEL[st]}: max R-hat over all BHM fits",
             f"results/benchmark_{st}.csv (model=bhm*, max of rhat_max)", fmt="{:.4f}")
        cite(f"conv.{st}.sampler", ", ".join(f"{k}={v}" for k, v in settings.items()),
             f"{STAGE_LABEL[st]}: NUTS settings used for every fold", f"results/benchmark_{st}.csv (mcmc_* columns)")
    df = pd.DataFrame(rows).set_index("corpus")
    df["model"] = df["model"].map(plain_label)
    df["stage"] = df["stage"].map(STAGE_LABEL)
    write_table(df, "convergence", "NUTS diagnostics for every zero-shot BHM fit.",
                notes="Same sampler settings for every fold (see numbers.md, conv.*.sampler).",
                group_col="stage")


def table_corpus_coverage(bench: dict[str, pd.DataFrame]) -> None:
    allb = pd.concat(bench.values()).dropna(subset=["corpus_cov94"])
    g = allb.groupby("model")["corpus_cov94"].agg(["sum", "count"])
    g = g.loc[ordered_models(g.index)]
    for m, r in g.iterrows():
        cite(f"zs.pooled.{m}.corpus_cov94", f"{int(r['sum'])}/{int(r['count'])}",
             f"Both stages, zero-shot, {plain_label(m)}: folds with corpus-level mean in 94% interval",
             "results/benchmark_{hf,sn}.csv (sum/count of corpus_cov94)")
    df = pd.DataFrame({"covered": g["sum"].astype(int), "folds": g["count"].astype(int)})
    df.index = [label(m) for m in df.index]
    write_table(df, "corpus_coverage_pooled",
                "Zero-shot corpus-level coverage pooled over both stages: folds whose held-out corpus's mean "
                "log runtime per character lies in the 94\\% predictive interval.",
                notes="One event per fold; cannot rank models.")


def table_prior_sensitivity() -> None:
    path = RES / "prior_sensitivity_sn.csv"
    if not path.exists():
        return
    ps = pd.read_csv(path, index_col="param")
    cite("prior.sn.max_abs_diff", ps["diff"].abs().max(),
         "String normalisation: max |posterior mean change| over parameters, gamma0 prior N(-14,2) vs N(-16,2) "
         "(log units)", "results/prior_sensitivity_sn.csv (max |diff|)", fmt="{:.4f}")
    cite("prior.sn.max_abs_diff_sd", ps["diff_in_sd"].abs().max(),
         "String normalisation: same, in posterior sd units", "results/prior_sensitivity_sn.csv (max |diff_in_sd|)",
         fmt="{:.3f}")
    df = ps[["mean_prod", "mean_alt", "diff", "diff_in_sd"]].rename(columns={
        "mean_prod": "Mean, N(-16,2)", "mean_alt": "Mean, N(-14,2)", "diff": "Change", "diff_in_sd": "Change / sd"})
    write_table(df, "prior_sensitivity",
                "String normalisation: posterior means under the production gamma0 prior and an alternative.",
                float_fmt="{:.3f}")

    lodo = RES / "prior_sensitivity_sn_lodo.csv"
    if lodo.exists():
        alt = pd.read_csv(lodo).set_index("corpus")["rt_mape"]
        base = load_benchmark("sn").query("model == 'bhm'").set_index("corpus")["rt_mape"]
        cmp_ = pd.DataFrame({"N(-16,2)": base, "N(-14,2)": alt.rename(index=short_corpus)})
        cmp_["Change"] = cmp_.iloc[:, 1] - cmp_.iloc[:, 0]
        cite("prior.sn.zs_rt_mape_median_alt", cmp_["N(-14,2)"].median(),
             "String normalisation, zero-shot BHM median runtime MAPE under gamma0 ~ N(-14,2) (%)",
             "results/prior_sensitivity_sn_lodo.csv (median rt_mape)")
        cite("prior.sn.zs_rt_mape_max_change", cmp_["Change"].abs().max(),
             "String normalisation, zero-shot BHM: max per-corpus |change| in runtime MAPE between priors (pp)",
             "results/prior_sensitivity_sn_lodo.csv vs results/benchmark_sn.csv")
        write_table(cmp_, "prior_sensitivity_zero_shot",
                    "String normalisation: zero-shot BHM runtime MAPE (\\%) per corpus under both gamma0 priors.")


# ── figures ──────────────────────────────────────────────────────────────────

def _style():
    plt.rcParams.update({
        "pdf.fonttype": 42, "font.size": 8, "axes.edgecolor": NEUTRAL, "axes.labelcolor": TEXT_2,
        "xtick.color": TEXT_2, "ytick.color": TEXT_2, "axes.titlesize": 9, "axes.titlecolor": TEXT,
        "axes.spines.top": False, "axes.spines.right": False, "figure.facecolor": "white",
    })


def fig_zero_shot_heatmap(bench: dict[str, pd.DataFrame]) -> None:
    cmap = LinearSegmentedColormap.from_list("blue", BLUE_RAMP)
    allv = pd.concat([b["rt_mape"] for b in bench.values()]).dropna()
    norm = LogNorm(vmin=max(allv.min(), 1), vmax=allv.max())
    heights = [len(ordered_models(b["model"].unique())) for b in bench.values()]
    fig, axes = plt.subplots(2, 1, figsize=(7.0, 0.22 * sum(heights) + 1.6),
                             gridspec_kw={"height_ratios": heights}, constrained_layout=True)
    for ax, (st, b) in zip(axes, bench.items()):
        wide = b.pivot(index="model", columns="corpus", values="rt_mape")
        wide = wide.loc[[m for m in ordered_models(wide.index) if wide.loc[m].notna().any()]]
        im = ax.imshow(wide.clip(lower=1).to_numpy(float), cmap=cmap, norm=norm, aspect="auto")
        for i in range(wide.shape[0]):
            for j in range(wide.shape[1]):
                v = wide.iat[i, j]
                dark = norm(max(v, 1)) > 0.55
                ax.text(j, i, f"{v:.0f}" if v >= 10 else f"{v:.1f}", ha="center", va="center", fontsize=6.5,
                        color="white" if dark else TEXT)
        groups = [MODEL_GROUP[m] for m in wide.index]
        for i in range(1, len(groups)):
            if groups[i] != groups[i - 1]:
                ax.axhline(i - 0.5, color="white", lw=2.5)
        ax.set_xticks(range(wide.shape[1]), wide.columns, rotation=30, ha="right")
        ax.set_yticks(range(wide.shape[0]), [plain_label(m) for m in wide.index])
        ax.tick_params(length=0)
        for s in ax.spines.values():
            s.set_visible(False)
        ax.set_title(f"{STAGE_LABEL[st]} — zero-shot runtime MAPE (%)", loc="left")
    cb = fig.colorbar(im, ax=axes, shrink=0.6, pad=0.01)
    cb.set_label("Runtime MAPE (%), log scale")
    cb.outline.set_visible(False)
    fig.savefig(OUT / "fig_zero_shot_error_per_corpus.pdf")
    plt.close(fig)


def fig_hw_share() -> None:
    regimes = [("in_sample", "In-sample\n(with τ)"), ("zero_shot", "Zero-shot"),
               ("anchored", "Anchored"), ("thesis_style", "Thesis-style\n(no τ)")]
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6), sharey=True, constrained_layout=True)
    rng = np.random.default_rng(0)
    for ax, st in zip(axes, ("hf", "sn")):
        hw = pd.read_csv(RES / f"hw_share_{st}.csv", index_col="corpus") * 100
        per = hw.drop(index=["median", "pooled"])
        for x, (col, _) in enumerate(regimes):
            v = per[col].dropna()
            if v.empty:
                ax.text(x, 50, "pending\nprobes", ha="center", va="center", color=TEXT_2, fontsize=7)
                continue
            ax.scatter(x + rng.uniform(-0.12, 0.12, len(v)), v, s=14, color=NEUTRAL,
                       edgecolors="white", linewidths=0.6, zorder=2)
            med = v.median()
            ax.plot([x - 0.25, x + 0.25], [med, med], color=BLUE, lw=2, solid_capstyle="round", zorder=3)
            ax.text(x + 0.28, med, f"{med:.1f}", va="center", fontsize=7, color=TEXT)
        ax.set_xticks(range(len(regimes)), [r for _, r in regimes])
        ax.set_xlim(-0.5, len(regimes) - 0.3)
        ax.set_ylim(-3, 103)
        ax.yaxis.grid(True, color=GRID, lw=0.6)
        ax.set_axisbelow(True)
        ax.set_title(STAGE_LABEL[st], loc="left")
    axes[0].set_ylabel("Hardware share of energy variance (%)")
    fig.text(0.01, -0.04, "Grey: one corpus. Blue: median across corpora.", fontsize=7, color=TEXT_2)
    fig.savefig(OUT / "fig_hw_share_by_regime.pdf", bbox_inches="tight")
    plt.close(fig)


def fig_pit() -> None:
    cal = {st: pd.read_csv(RES / f"calibration_{st}.csv") for st in ("hf", "sn")}
    models = ordered_models(cal["hf"]["model"].unique())
    fig, axes = plt.subplots(2, len(models), figsize=(7.0, 2.8), sharex=True, sharey=True, constrained_layout=True)
    bins = np.linspace(0, 1, 11)
    for r, st in enumerate(("hf", "sn")):
        for c, m in enumerate(models):
            ax = axes[r, c]
            g = cal[st][cal[st]["model"] == m]
            ax.hist(g["pit"], bins=bins, density=True, color=BLUE, edgecolor="white", linewidth=1)
            ax.axhline(1, color=TEXT_2, lw=0.8, ls="--")
            ax.text(0.5, 0.97, f"{100 * g['in_hdi94'].mean():.0f}% in 94%", transform=ax.transAxes,
                    ha="center", va="top", fontsize=6.5, color=TEXT_2)
            if r == 0:
                ax.set_title(plain_label(m), fontsize=7.5)
            if c == 0:
                ax.set_ylabel(f"{'Filtering' if st == 'hf' else 'Normalisation'}\ndensity")
            ax.set_xticks([0, 0.5, 1])
    fig.supxlabel("PIT of measured runtime (uniform = calibrated)", fontsize=8, color=TEXT_2)
    fig.savefig(OUT / "fig_pit_in_sample.pdf")
    plt.close(fig)


# ── main ─────────────────────────────────────────────────────────────────────

def write_numbers(bench: dict[str, pd.DataFrame]) -> None:
    for st, b in bench.items():
        cite(f"data.{st}.n_jobs", int(pd.read_csv(RES / ("df_train_hf.csv" if st == "hf" else
                                                         "df_train_str_norm.csv")).shape[0]),
             f"{STAGE_LABEL[st]}: runtime jobs", "results/df_train_hf.csv" if st == "hf"
             else "results/df_train_str_norm.csv", fmt="{:d}")
        cite(f"data.{st}.n_folds", b["corpus"].nunique(), f"{STAGE_LABEL[st]}: zero-shot folds (corpora)",
             f"results/benchmark_{st}.csv", fmt="{:d}")
    lines = ["# Numbers cited in the paper", "",
             "Generated by `make_paper_assets.py` — regenerate, don't edit. Sources are relative to `model/`.", "",
             "| key | value | description | source |", "|---|---|---|---|"]
    lines += [f"| `{n['key']}` | {n['value']} | {n['description']} | `{n['source']}` |" for n in NUMBERS]
    (OUT / "numbers.md").write_text("\n".join(lines) + "\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    _style()
    bench = {st: load_benchmark(st) for st in ("hf", "sn")}
    table_zero_shot(bench)
    table_per_corpus(bench)
    table_corpus_coverage(bench)
    table_hw_share()
    table_calibration()
    table_convergence(bench)
    table_prior_sensitivity()
    fig_zero_shot_heatmap(bench)
    fig_hw_share()
    fig_pit()
    write_numbers(bench)
    print(f"wrote {len(list(OUT.iterdir()))} files to {OUT} ({len(NUMBERS)} cited numbers)")


if __name__ == "__main__":
    main()
